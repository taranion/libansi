package org.prelle.ansi;

/**
 * See https://en.wikipedia.org/wiki/ANSI_escape_code#SGR
 */
public enum SGRCode {

	RESET(0),
	BOLD(1),
	FAINT(2),
	ITALIC(3),
	UNDERLINE(4),
	SLOW_BLINK(5),
	RAPID_BLINK(6),
	INVERT(7),
	INVISIBLE(8),
	CROSSED_OUT(9),
	PRIMARY_FONT(10),
	GOTHIC(20),
	DOUBLE_UNDERLINE(21),
	NORMAL_INTENSITY(22),
	ITALIC_OFF(23),
	UNDERLINE_OFF(24),
	BLINKING_OFF(25),
	PROPORTIONAL_SPACING(26),
	INVERT_OFF(27),
	INVISIBLE_OFF(28),
	CROSSED_OUT_OFF(29),
	FOREGROUND01(30),
	FOREGROUND02(31),
	FOREGROUND03(32),
	FOREGROUND04(33),
	FOREGROUND05(34),
	FOREGROUND06(35),
	FOREGROUND07(36),
	FOREGROUND08(37),
	FOREGROUND_DEFAULT(38),
	FOREGROUND_VARIABLE(39),
	BACKGROUND01(40),
	BACKGROUND02(41),
	BACKGROUND03(42),
	BACKGROUND04(43),
	BACKGROUND05(44),
	BACKGROUND06(45),
	BACKGROUND07(46),
	BACKGROUND08(47),
	BACKGROUND_DEFAULT(48),
	BACKGROUND_VARIABLE(49),
	PROPORTIONAL_SPACING_OFF(50),
	FRAMED(51),
	ENCIRCLED(52),
	OVERLINED(53),
	FRAMED_ENCIRCLED_OFF(54),
	FOREGROUND_BRIGHT01(90),
	FOREGROUND_BRIGHT02(91),
	FOREGROUND_BRIGHT03(92),
	FOREGROUND_BRIGHT04(93),
	FOREGROUND_BRIGHT05(94),
	FOREGROUND_BRIGHT06(95),
	FOREGROUND_BRIGHT07(96),
	FOREGROUND_BRIGHT08(97),
	BACKGROUND_BRIGHT01(100),
	BACKGROUND_BRIGHT02(101),
	BACKGROUND_BRIGHT03(102),
	BACKGROUND_BRIGHT04(103),
	BACKGROUND_BRIGHT05(104),
	BACKGROUND_BRIGHT06(105),
	BACKGROUND_BRIGHT07(106),
	BACKGROUND_BRIGHT08(107),

	;

	int value;

	SGRCode(int val) {
		this.value = val;
	}

	//-------------------------------------------------------------------
	public static SGRCode valueOf(int code) {
		for (SGRCode func : SGRCode.values()) {
			if (func.value==code)
				return func;
		}
		throw new IllegalArgumentException("Not a valid SGR code: "+code);
	}

}
